// Writes assets/site-config.js from environment variables, so deploy-time settings reach
// the static pages without a build step. Run by the deploy workflow; locally:
//   GA_MEASUREMENT_ID=G-XXXX API_BASE=https://api.codilated.com node scripts/write-site-config.mjs
// Unset variables write empty values, which switch the feature off (no analytics / same-origin API).
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const env = process.env;
const config = {
	gaMeasurementId: (env.GA_MEASUREMENT_ID || env.VITE_GA_MEASUREMENT_ID || '').trim(),
	apiBase: (env.API_BASE || '').trim().replace(/\/+$/, '')
};

if (config.gaMeasurementId && !/^G-[A-Z0-9]+$/i.test(config.gaMeasurementId)) {
	console.error(`GA_MEASUREMENT_ID "${config.gaMeasurementId}" is not a GA4 ID (G-XXXXXXX)`);
	process.exit(1);
}
if (config.apiBase && !/^https:\/\/[^/\s]+/.test(config.apiBase)) {
	console.error(`API_BASE "${config.apiBase}" must be an https:// origin`);
	process.exit(1);
}

const out = fileURLToPath(new URL('../assets/site-config.js', import.meta.url));
writeFileSync(
	out,
	'/* Generated by scripts/write-site-config.mjs — edit the environment, not this file. */\n' +
		`window.CODILATED_CONFIG = ${JSON.stringify(config, null, '\t')};\n`
);
console.log(`wrote ${out}:`, config);
